// D-86: writes the schema of a TOP4HoneyChains database (tables with keys, checks, defaults and indexes, then the foreign keys,
// then the triggers) as one T-SQL script for SQL Server 2019. The SSMS diagram objects are left out.
// D-98: the install mode writes db/install for a new, empty database: 01_schema.sql (the same schema, every object guarded with
// IF NOT EXISTS) and 02_reference_data.sql (the lookup and configuration rows of InstallData.Tables, never a table with people).
// Both modes only read the source database.
// Usage:
//   dotnet run --project tools/DemoSchema -- "<connection string>" db/demo/schema.sql
//   dotnet run --project tools/DemoSchema -- install "<connection string>" db/install
var install = args.Length == 3 && args[0] == "install";
if (args.Length != 2 && !install)
{
    Console.Error.WriteLine("usage: DemoSchema \"<connection string>\" <output.sql>");
    Console.Error.WriteLine("       DemoSchema install \"<connection string>\" <output folder>");
    return 1;
}
var connectionString = install ? args[1] : args[0];
var output = install ? args[2] : args[1];

var databaseName = new SqlConnectionStringBuilder(connectionString).InitialCatalog;
var server = new Server(new ServerConnection(new SqlConnection(connectionString)));
var db = server.Databases[databaseName] ?? throw new InvalidOperationException("database not found: " + databaseName);
var lastMigration = Repo.LastMigration(output);

var common = new ScriptingOptions
{
    TargetServerVersion = SqlServerVersion.Version150,
    SchemaQualify = true,
    AnsiPadding = false,
    NoCollation = false,
    NoFileGroup = true,
    Permissions = false,
    ExtendedProperties = false,
    IncludeHeaders = false,
    AllowSystemObjects = false,
    // install mode: every table, constraint, index, key and trigger only when it does not exist yet (the script can run again)
    IncludeIfNotExists = install
};

ScriptingOptions With(Action<ScriptingOptions> change)
{
    var o = new ScriptingOptions(common);
    change(o);
    return o;
}

var tableOptions = With(o =>
{
    o.DriPrimaryKey = true;
    o.DriUniqueKeys = true;
    o.DriChecks = true;
    o.DriDefaults = true;
    o.DriForeignKeys = false;
    o.ClusteredIndexes = true;
    o.NonClusteredIndexes = true;
    o.Indexes = true;
    o.Triggers = false;
});

var tables = db.Tables.Cast<Table>()
    .Where(t => !t.IsSystemObject && t.Name != "sysdiagrams")
    .OrderBy(t => t.Name, StringComparer.Ordinal)
    .ToList();

var sql = new StringBuilder();
if (install)
{
    sql.AppendLine($"-- TOP4HoneyChains database schema after db/migrations up to {lastMigration}, for a new, empty database (D-98, db/install).");
    sql.AppendLine($"-- Generated by tools/DemoSchema (install mode) from the database {databaseName}; schema only, no rows. Do not edit by hand.");
    sql.AppendLine("-- Every object is created only when it does not exist, so the script can run again. SQL Server 2019, compatibility level 140 or 150.");
    sql.AppendLine("-- Run: sqlcmd -S <server> -d <new database> -E -I -f 65001 -b -i db\\install\\01_schema.sql   (docs/KURULUM-TR.md, part B)");
    sql.AppendLine();
    sql.AppendLine(InstallData.Guard);
}
else
{
    sql.AppendLine($"-- TOP4HoneyChains database schema after db/migrations up to {lastMigration} (D-86, demo database).");
    sql.AppendLine($"-- Generated by tools/DemoSchema from the local database {databaseName}; schema only, no rows. Do not edit by hand.");
    sql.AppendLine("-- SQL Server 2019; runs at compatibility level 140 or 150.");
    sql.AppendLine();
}

void Emit(StringCollection statements)
{
    foreach (var s in statements)
    {
        if (s == null || s.StartsWith("SET ANSI_PADDING", StringComparison.Ordinal))
            continue;
        sql.AppendLine((install ? Repo.GuardByStructure(s) : s).TrimEnd());
        sql.AppendLine("GO");
    }
}

sql.AppendLine("-------------------------------------------------------------------- tables");
foreach (var t in tables)
    Emit(t.Script(tableOptions));

sql.AppendLine("-------------------------------------------------------------------- foreign keys");
foreach (var t in tables)
    foreach (var fk in t.ForeignKeys.Cast<ForeignKey>().OrderBy(f => f.Name, StringComparer.Ordinal))
        Emit(fk.Script(common));

sql.AppendLine("-------------------------------------------------------------------- triggers");
foreach (var t in tables)
    foreach (var tr in t.Triggers.Cast<Trigger>().OrderBy(x => x.Name, StringComparer.Ordinal))
        Emit(tr.Script(common));

var others = db.Views.Cast<View>().Count(v => !v.IsSystemObject)
             + db.UserDefinedFunctions.Cast<UserDefinedFunction>().Count(f => !f.IsSystemObject && f.Name != "fn_diagramobjects")
             + db.StoredProcedures.Cast<StoredProcedure>().Count(p => !p.IsSystemObject && !p.Name.Contains("diagram", StringComparison.Ordinal));
if (others > 0)
    throw new InvalidOperationException($"{others} views, functions or procedures exist; extend tools/DemoSchema to script them.");

if (install)
{
    sql.AppendLine("SET NOEXEC OFF;");
    sql.AppendLine("GO");
}

if (!install)
{
    Repo.Write(output, sql.ToString());
    Console.WriteLine($"{tables.Count} tables, written to {output}");
    return 0;
}

Directory.CreateDirectory(output);
Repo.Write(Path.Combine(output, "01_schema.sql"), sql.ToString());
Console.WriteLine($"{tables.Count} tables, written to {Path.Combine(output, "01_schema.sql")}");

await using (var conn = new SqlConnection(connectionString))
{
    await conn.OpenAsync();
    var (script, counts) = await InstallData.ScriptAsync(conn, databaseName, lastMigration);
    Repo.Write(Path.Combine(output, "02_reference_data.sql"), script);
    foreach (var (table, rows) in counts)
        Console.WriteLine($"  {table}: {rows} rows");
    Console.WriteLine($"{counts.Count} reference tables, {counts.Sum(c => c.Rows)} rows, written to {Path.Combine(output, "02_reference_data.sql")}");
}
return 0;

static class Repo
{
    // the newest script in db/migrations, found from the output path upwards
    public static string LastMigration(string output)
    {
        for (var dir = new DirectoryInfo(Path.GetFullPath(output)); dir != null; dir = dir.Parent)
        {
            var migrations = Path.Combine(dir.FullName, "db", "migrations");
            if (Directory.Exists(migrations))
                return Directory.GetFiles(migrations, "*.sql").Select(Path.GetFileName).OrderBy(n => n, StringComparer.Ordinal).LastOrDefault() ?? "(none)";
        }
        return "(db/migrations not found)";
    }

    // A default without a name of its own gets a new system name on every database, so SMO's guard by name would add it again
    // on the second run. Every default is therefore guarded by its column instead.
    private static readonly System.Text.RegularExpressions.Regex DefaultStatement = new(
        @"^IF NOT EXISTS \(SELECT \* FROM sys\.objects WHERE object_id = OBJECT_ID\(N'[^']+'\) AND type = 'D'\)(\r?\nBEGIN\r?\nALTER TABLE \[dbo\]\.\[(?<table>[^\]]+)\] ADD\s+(CONSTRAINT \[[^\]]+\]\s+)?DEFAULT .* FOR \[(?<column>[^\]]+)\]\r?\nEND)\s*$",
        System.Text.RegularExpressions.RegexOptions.Singleline);

    // The same holds for a CHECK or FOREIGN KEY without a name of its own: it is guarded by its definition, or by its column and
    // the table it refers to.
    private static readonly System.Text.RegularExpressions.Regex UnnamedCheck = new(
        @"^IF NOT EXISTS \(SELECT \* FROM sys\.check_constraints WHERE [^\r\n]*\)(?<rest>\r?\nALTER TABLE \[dbo\]\.\[(?<table>[^\]]+)\]\s+WITH (NO)?CHECK ADD CHECK\s+\((?<def>.*)\))\s*$",
        System.Text.RegularExpressions.RegexOptions.Singleline);
    private static readonly System.Text.RegularExpressions.Regex UnnamedForeignKey = new(
        @"^IF NOT EXISTS \(SELECT \* FROM sys\.foreign_keys WHERE [^\r\n]*\)(?<rest>\r?\nALTER TABLE \[dbo\]\.\[(?<table>[^\]]+)\]\s+WITH (NO)?CHECK ADD FOREIGN KEY\(\[(?<column>[^\]]+)\]\)\r?\nREFERENCES \[dbo\]\.\[(?<target>[^\]]+)\].*)$",
        System.Text.RegularExpressions.RegexOptions.Singleline);

    public static string GuardByStructure(string statement)
    {
        var m = DefaultStatement.Match(statement);
        if (m.Success)
        {
            var table = m.Groups["table"].Value;
            var column = m.Groups["column"].Value;
            return $"IF NOT EXISTS (SELECT 1 FROM sys.default_constraints WHERE parent_object_id = OBJECT_ID(N'[dbo].[{table}]') AND parent_column_id = COLUMNPROPERTY(OBJECT_ID(N'[dbo].[{table}]'), N'{column}', 'ColumnId'))"
                   + m.Groups[1].Value;
        }
        m = UnnamedCheck.Match(statement);
        if (m.Success)
            return $"IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'[dbo].[{m.Groups["table"].Value}]') AND definition = N'{m.Groups["def"].Value.Replace("'", "''")}')"
                   + m.Groups["rest"].Value;
        m = UnnamedForeignKey.Match(statement);
        if (m.Success)
            return $"IF NOT EXISTS (SELECT 1 FROM sys.foreign_key_columns WHERE parent_object_id = OBJECT_ID(N'[dbo].[{m.Groups["table"].Value}]') AND COL_NAME(parent_object_id, parent_column_id) = N'{m.Groups["column"].Value}' AND referenced_object_id = OBJECT_ID(N'[dbo].[{m.Groups["target"].Value}]'))"
                   + m.Groups["rest"].Value;
        return statement;
    }

    public static void Write(string path, string text) =>
        File.WriteAllText(path, text.Replace("\r\n", "\n").Replace("\n", "\r\n"), new UTF8Encoding(true));
}

// D-98: the reference rows a new installation starts with. Only lookup and configuration tables, in dependency order; never a
// table that holds people, accounts, beekeepers, organizations, lots, batches, files, consents or audit rows. A column that
// names a user is written as NULL. Rows are written with their keys and inserted only when the key is missing.
static class InstallData
{
    public record Spec(string Table, string? Where = null, string[]? NullColumns = null, string? Why = null);

    // Translations of rows that are not exported (production periods, parameter contents) are left out with them.
    private const string TranslationWhere =
        "Entity NOT IN (N'ProductionPeriod', N'ParameterContent')" +
        " AND (Entity <> N'HoneyType' OR EXISTS (SELECT 1 FROM dbo.HoneyTypes x WHERE CAST(x.HoneyTypeId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'Ccp' OR EXISTS (SELECT 1 FROM dbo.CriticalControlPoints x WHERE CAST(x.Id AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'Parameter' OR EXISTS (SELECT 1 FROM dbo.CriticalControlPointParameters x WHERE CAST(x.ParameterId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'ParameterLimit' OR EXISTS (SELECT 1 FROM dbo.CriticalControlPointParameterLimits x WHERE CAST(x.LimitId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'ParameterCategory' OR EXISTS (SELECT 1 FROM dbo.CriticalControlPointParameterCategories x WHERE CAST(x.CategoryId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'EducationLevel' OR EXISTS (SELECT 1 FROM dbo.BeekeeperEducationLevels x WHERE CAST(x.BeekeeperEducationLevelId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'BeekeepingPurposeType' OR EXISTS (SELECT 1 FROM dbo.BeekeepingPurposeTypes x WHERE CAST(x.BeekeepingPurposeTypeId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'BeekeepingType' OR EXISTS (SELECT 1 FROM dbo.BeekeepingTypes x WHERE CAST(x.BeekeepingTypeId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'AssignmentStatus' OR EXISTS (SELECT 1 FROM dbo.AssignmentStatuses x WHERE CAST(x.AssignmentStatusId AS nvarchar(50)) = EntityKey))" +
        " AND (Entity <> N'Capability' OR EXISTS (SELECT 1 FROM dbo.Capabilities x WHERE x.Code = EntityKey))" +
        " AND (Entity <> N'OrgRole' OR EXISTS (SELECT 1 FROM dbo.OrgRoles x WHERE x.Code = EntityKey))";

    public static readonly Spec[] Tables =
    {
        new("__EFMigrationsHistory", Why: "the Identity tables are already at their EF migration"),
        new("AspNetRoles", "NormalizedName IN (N'ADMINISTRATOR', N'BEEKEEPER')", Why: "the global roles the code uses (D-60: the others are retired)"),
        new("AssignmentStatuses"),
        new("HoneyTypes"),
        new("BeekeeperEducationLevels"),
        new("BeekeepingPurposeTypes"),
        new("BeekeepingTypes"),
        new("Capabilities"),
        new("OrgRoles"),
        new("CriticalControlPoints"),
        new("CriticalControlPointParameterCategories"),
        new("CriticalControlPointParameters"),
        new("CriticalControlPointParameterLimits"),
        new("CcpResponsibilities", NullColumns: new[] { "UpdatedByUserId" }),
        new("CcpResponsibilityCapabilities"),
        new("CcpResponsibilityRoles"),
        new("Provinces"),
        new("Districts"),
        new("RolePermissions", NullColumns: new[] { "UpdatedByUserId" }),
        new("ReferenceTranslations", TranslationWhere, new[] { "UpdatedByUserId" }),
        new("Notices", "OrgId IS NULL AND IsDraft = 1 AND PublishedByUserId IS NULL", new[] { "PublishedByUserId" },
            "the platform's draft notices seeded by 020 and 029; published versions belong to the instance's data-protection office")
    };

    // Not exported, on purpose: RawHoneyProductionPeriods (seasons are created by each installation's administrators; the local rows
    // include a season of the live-like cast) and CriticalControlPointParameterContents (their videos are uploads outside the repository).

    // Runs first in both scripts: refuses a system database and a database that already has accounts (the live one or an installed one)
    public const string Guard = """
        SET NOCOUNT ON;
        DECLARE @users int = 0;
        IF OBJECT_ID(N'dbo.AspNetUsers', N'U') IS NOT NULL
            EXEC sys.sp_executesql N'SELECT @n = COUNT(*) FROM dbo.AspNetUsers', N'@n int OUTPUT', @n = @users OUTPUT;
        IF DB_NAME() IN (N'master', N'model', N'msdb', N'tempdb')
        BEGIN
            RAISERROR(N'db/install: run this script in the new, empty TOP4HoneyChains database (sqlcmd -d <database>), not in %s.', 16, 1, N'a system database');
            SET NOEXEC ON;
        END;
        ELSE IF @users > 0
        BEGIN
            RAISERROR(N'db/install: this database already has user accounts. db/install is only for a new, empty database; an existing database is updated with db/migrations.', 16, 1);
            SET NOEXEC ON;
        END;
        GO
        """;

    private static readonly string[] TestMarkers = { "zz_", "zz ", "[demo]", "@example.invalid" };

    public static async Task<(string Script, List<(string Table, int Rows)> Counts)> ScriptAsync(SqlConnection conn, string databaseName, string lastMigration)
    {
        var sql = new StringBuilder();
        sql.AppendLine($"-- TOP4HoneyChains reference data after db/migrations up to {lastMigration}, for a new, empty database (D-98, db/install).");
        sql.AppendLine($"-- Generated by tools/DemoSchema (install mode) from the database {databaseName}; lookup and configuration tables only. Do not edit by hand.");
        sql.AppendLine("-- Each row is inserted only when its key is missing, so the script can run again. Run it after 01_schema.sql:");
        sql.AppendLine("--   sqlcmd -S <server> -d <new database> -E -I -f 65001 -b -i db\\install\\02_reference_data.sql   (docs/KURULUM-TR.md, part B)");
        sql.AppendLine("-- Tables:");
        foreach (var t in Tables)
            sql.AppendLine($"--   {t.Table}{(t.Where != null && t.Table != "ReferenceTranslations" ? " where " + t.Where : "")}{(t.NullColumns != null ? " (" + string.Join(", ", t.NullColumns) + " not copied)" : "")}{(t.Why != null ? ": " + t.Why : "")}");
        sql.AppendLine("--   ReferenceTranslations: only translations of the rows above (not of production periods or parameter contents)");
        sql.AppendLine("-- Not exported: RawHoneyProductionPeriods (each installation creates its seasons) and CriticalControlPointParameterContents (uploaded videos).");
        sql.AppendLine();
        sql.AppendLine(Guard);

        var counts = new List<(string, int)>();
        foreach (var spec in Tables)
        {
            var columns = await ColumnsAsync(conn, spec.Table);
            var keys = await KeyColumnsAsync(conn, spec.Table);
            if (keys.Count == 0)
                throw new InvalidOperationException($"{spec.Table} has no primary key; the install script needs one to stay idempotent.");
            var identity = Convert.ToInt32(await new SqlCommand($"SELECT COUNT(*) FROM sys.identity_columns WHERE object_id = OBJECT_ID(N'dbo.[{spec.Table}]')", conn).ExecuteScalarAsync()) > 0;

            var rows = new List<string>();
            var select = $"SELECT {string.Join(", ", columns.Select(c => $"[{c.Name}]"))} FROM dbo.[{spec.Table}]"
                         + (spec.Where != null ? " WHERE " + spec.Where : "") + $" ORDER BY {string.Join(", ", keys.Select(k => $"[{k}]"))}";
            await using (var cmd = new SqlCommand(select, conn))
            await using (var r = await cmd.ExecuteReaderAsync())
            {
                while (await r.ReadAsync())
                {
                    var values = new List<string>();
                    for (var i = 0; i < columns.Count; i++)
                    {
                        var c = columns[i];
                        if (spec.NullColumns?.Contains(c.Name) == true || r.IsDBNull(i))
                        {
                            values.Add("NULL");
                            continue;
                        }
                        var value = r.GetValue(i);
                        if (value is string s && TestMarkers.Any(m => s.StartsWith(m, StringComparison.OrdinalIgnoreCase) || (m.StartsWith('@') && s.Contains(m, StringComparison.OrdinalIgnoreCase))))
                            throw new InvalidOperationException(
                                $"{spec.Table} has a row that looks like test data (key {string.Join(",", keys.Select(k => r[k]))}, column {c.Name}). Remove it from the source database or filter it in tools/DemoSchema.");
                        values.Add(Literal(value, c.Type));
                    }
                    rows.Add("(" + string.Join(", ", values) + ")");
                }
            }
            counts.Add((spec.Table, rows.Count));

            sql.AppendLine($"-------------------------------------------------------------------- {spec.Table} ({rows.Count} rows)");
            if (rows.Count == 0)
                continue;
            var list = string.Join(", ", columns.Select(c => $"[{c.Name}]"));
            var match = string.Join(" AND ", keys.Select(k => $"t.[{k}] = v.[{k}]"));
            foreach (var chunk in rows.Chunk(200))
            {
                if (identity)
                    sql.AppendLine($"SET IDENTITY_INSERT dbo.[{spec.Table}] ON;");
                sql.AppendLine($"INSERT INTO dbo.[{spec.Table}] ({list})");
                sql.AppendLine($"SELECT {string.Join(", ", columns.Select(c => $"v.[{c.Name}]"))} FROM (VALUES");
                sql.AppendLine(string.Join(",\n", chunk));
                sql.AppendLine($") AS v ({list})");
                sql.AppendLine($"WHERE NOT EXISTS (SELECT 1 FROM dbo.[{spec.Table}] t WHERE {match});");
                sql.AppendLine($"PRINT CONCAT(N'{spec.Table}: ', @@ROWCOUNT, N' rows added');");
                if (identity)
                    sql.AppendLine($"SET IDENTITY_INSERT dbo.[{spec.Table}] OFF;");
                sql.AppendLine("GO");
            }
        }
        sql.AppendLine("SET NOEXEC OFF;");
        sql.AppendLine("GO");
        return (sql.ToString(), counts);
    }

    private record Column(string Name, string Type);

    private static async Task<List<Column>> ColumnsAsync(SqlConnection conn, string table)
    {
        var list = new List<Column>();
        await using var cmd = new SqlCommand(
            "SELECT c.name, t.name FROM sys.columns c JOIN sys.types t ON t.user_type_id = c.user_type_id WHERE c.object_id = OBJECT_ID(@t) AND c.is_computed = 0 ORDER BY c.column_id", conn);
        cmd.Parameters.AddWithValue("@t", $"dbo.[{table}]");
        await using var r = await cmd.ExecuteReaderAsync();
        while (await r.ReadAsync())
            list.Add(new Column(r.GetString(0), r.GetString(1)));
        if (list.Count == 0)
            throw new InvalidOperationException("table not found: " + table);
        return list;
    }

    private static async Task<List<string>> KeyColumnsAsync(SqlConnection conn, string table)
    {
        var list = new List<string>();
        await using var cmd = new SqlCommand(@"
SELECT c.name FROM sys.indexes i
JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
WHERE i.object_id = OBJECT_ID(@t) AND i.is_primary_key = 1 ORDER BY ic.key_ordinal", conn);
        cmd.Parameters.AddWithValue("@t", $"dbo.[{table}]");
        await using var r = await cmd.ExecuteReaderAsync();
        while (await r.ReadAsync())
            list.Add(r.GetString(0));
        return list;
    }

    // A T-SQL literal on one line: line breaks become NCHAR(13)/NCHAR(10) and "$(" is split, so neither sqlcmd's batch
    // separator nor its variables can be triggered by a value.
    private static string Literal(object value, string type) => type switch
    {
        "char" or "varchar" or "nchar" or "nvarchar" or "text" or "ntext" or "sysname" => Text((string)value),
        "bit" => (bool)value ? "1" : "0",
        "tinyint" or "smallint" or "int" or "bigint" => Convert.ToString(value, CultureInfo.InvariantCulture)!,
        "decimal" or "numeric" or "money" or "smallmoney" => ((decimal)value).ToString(CultureInfo.InvariantCulture),
        "float" => ((double)value).ToString("R", CultureInfo.InvariantCulture),
        "real" => ((float)value).ToString("R", CultureInfo.InvariantCulture),
        "date" => $"'{(DateTime)value:yyyy-MM-dd}'",
        "datetime" or "smalldatetime" => $"'{((DateTime)value).ToString("yyyy-MM-ddTHH:mm:ss.fff", CultureInfo.InvariantCulture)}'",
        "datetime2" => $"'{((DateTime)value).ToString("yyyy-MM-ddTHH:mm:ss.fffffff", CultureInfo.InvariantCulture)}'",
        "datetimeoffset" => $"'{((DateTimeOffset)value).ToString("yyyy-MM-ddTHH:mm:ss.fffffffzzz", CultureInfo.InvariantCulture)}'",
        "time" => $"'{(TimeSpan)value:hh\\:mm\\:ss\\.fffffff}'",
        "uniqueidentifier" => $"'{(Guid)value}'",
        "binary" or "varbinary" => "0x" + Convert.ToHexString((byte[])value),
        _ => throw new InvalidOperationException("no literal for SQL type " + type)
    };

    private static string Text(string s)
    {
        var parts = new List<string>();
        var current = new StringBuilder();
        void Flush()
        {
            if (current.Length > 0)
                parts.Add("N'" + current.ToString().Replace("'", "''").Replace("$(", "$' + N'(") + "'");
            current.Clear();
        }
        foreach (var ch in s)
        {
            if (ch is '\r' or '\n')
            {
                Flush();
                parts.Add(ch == '\r' ? "NCHAR(13)" : "NCHAR(10)");
            }
            else
                current.Append(ch);
        }
        Flush();
        if (parts.Count == 0)
            return "N''";
        if (parts.Count == 1 && !parts[0].Contains(" + ", StringComparison.Ordinal))
            return parts[0];
        // nvarchar(max) first, so the concatenation never cuts a long text at 4000 characters
        return "CAST(N'' AS nvarchar(max)) + " + string.Join(" + ", parts);
    }
}
